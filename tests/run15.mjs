// check-bank.mjs の検査：良い問題は通り、悪い問題はそれぞれ検出される
import { checkBanks, loadAppConfig } from '../tools/check-bank.mjs';
const log=[];const ok=(c,m)=>log.push((c?'PASS ':'FAIL ')+m);
const cfg=loadAppConfig();
ok(cfg.FIELDS.length===6&&cfg.FIELDS.every(f=>f.topics.length>0),'FIELDS read from index.html: 6 fields, all with topics');
const uniq=(i,k=0,len=16)=>Array.from({length:len},(_,j)=>String.fromCharCode(0x4e00+i*300+k*50+j)).join('');
const good=(i,topic='探索アルゴリズム')=>({q:'問'+i+'：'+uniq(i)+'を求めよ。',choices:['甲'+uniq(i,1),'乙'+uniq(i,2),'丙'+uniq(i,3),'丁'+uniq(i,4)],answer:i%4,explanation:'この問題の正解の根拠は、'+uniq(i,5,24)+'だからである。',topic,volatile:false,createdAt:'2026-11-09'});
const bank=(field,qs)=>({field,updatedAt:'2026-11-09',questions:qs});
const run=(qs,field='a-tech-basic')=>checkBanks({[field]:bank(field,qs)},cfg);
const has=(r,re)=>r.errors.some(e=>re.test(e));
let r=run([good(1),good(2),good(3)]);
ok(r.errors.length===0,'clean bank has no errors: '+r.errors.join('|'));
r=run([{...good(1),topic:'存在しないテーマ'}]);ok(has(r,/固定リストにありません/),'unknown topic detected');
r=run([{...good(1),choices:['同じ','同じ','丙','丁']}]);ok(has(r,/同じものがあります/),'duplicate choices detected');
r=run([{...good(1),choices:['ア. 甲','乙','丙','丁']}]);ok(has(r,/記号があります/),'label prefix detected');
r=run([{...good(1),answer:4}]);ok(has(r,/answer/),'bad answer index detected');
r=run([{...good(1),choices:['甲','乙','丙']}]);ok(has(r,/4つ/),'3 choices detected');
r=run([{...good(1),q:'```\nx ← 1\n問題'}]);ok(has(r,/閉じていません/),'unclosed fence detected');
r=run([{...good(1),choices:['`a','b','c','d']}]);ok(has(r,/閉じていません/),'unclosed inline code detected');
r=run([{...good(1),choices:['```\nx\n```','b','c','d']}]);ok(has(r,/コードブロック/),'fence in choice detected');
const d1=good(1),d2={...good(1),q:d1.q+'なお。'};
r=run([d1,d2]);ok(has(r,/内容が近い/),'near-duplicate question detected');
const sameAns=(i)=>({...good(i),choices:['共通の正解となる長い語句',...good(i).choices.slice(1)],answer:0});
r=run([sameAns(10),sameAns(11)]);ok(has(r,/正解が同じ/),'same meaningful answer detected');
const num=i=>({...good(i),choices:['1024','甲'+uniq(i,2),'乙'+uniq(i,3),'丙'+uniq(i,4)],answer:0});
r=run([num(20),num(21)]);ok(!has(r,/正解が同じ/),'short numeric answers are not treated as duplicates');
r=checkBanks({'a-tech-basic':bank('a-tech-basic',[good(30)]),'a-security':bank('a-security',[{...good(30),topic:'脅威と攻撃手法'}])},cfg);
ok(has(r,/内容が近い/),'duplicate across fields detected');
r=run([{...good(1),explanation:'短い'}]);ok(r.warns.some(w=>/解説が短い/.test(w)),'short explanation warned');
r=run([{...good(1),choices:['甲','乙','丙','必ず丁になる']}]);ok(r.warns.some(w=>/断定語/.test(w)),'absolute word in wrong choice warned');
r=run([{...good(1),q:'Ａ問題'}]);ok(r.warns.some(w=>/全角/.test(w)),'full-width alnum warned');
r=checkBanks({'zzz':bank('zzz',[good(1)])},cfg);ok(has(r,/FIELDS にありません/),'unknown field id detected');
r=checkBanks({'a-tech-basic':{...bank('a-tech-basic',[good(1)]),updatedAt:'昨日'}},cfg);ok(has(r,/updatedAt/),'bad updatedAt detected');
console.log(log.join('\n'));process.exit(log.some(l=>l.startsWith('FAIL'))?1:0);
